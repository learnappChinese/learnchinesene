-- Staged curriculum v2; additive only. NOT auto-activated for learners.
-- Existing duo_* / lexicon_* and user progression remain the source of truth.
create table if not exists public.learning_curriculum_versions (
  id bigint generated by default as identity primary key,
  version_code text not null unique,
  title text not null,
  status text not null default 'draft'
    check (status in ('draft','review','pilot','active','archived')),
  created_at timestamptz not null default now(),
  activated_at timestamptz
);

create table if not exists public.learning_unit_plans_v2 (
  id bigint generated by default as identity primary key,
  curriculum_version_id bigint not null references public.learning_curriculum_versions(id) on delete restrict,
  legacy_unit_id text not null references public.duo_units(id) on delete restrict,
  title text not null,
  objective_vi text not null,
  lesson_plan jsonb not null default '{}'::jsonb check (jsonb_typeof(lesson_plan)='object'),
  quality_status text not null default 'draft'
    check (quality_status in ('draft','needs_review','approved','rejected')),
  content_fingerprint text,
  quality_notes text,
  updated_at timestamptz not null default now(),
  unique (curriculum_version_id, legacy_unit_id)
);

create table if not exists public.learning_unit_content_v2 (
  unit_plan_id bigint not null references public.learning_unit_plans_v2(id) on delete cascade,
  content_kind text not null check (content_kind in ('word','challenge')),
  content_id text not null,
  phase text not null check (phase in ('preview','comprehension','retrieval','listening','production','hanzi','speaking','checkpoint','boss','review')),
  display_order integer not null check (display_order >= 0),
  is_required boolean not null default true,
  primary key (unit_plan_id,content_kind,content_id,phase),
  unique (unit_plan_id,phase,display_order,content_kind)
);

create index if not exists learning_unit_plans_v2_status_idx on public.learning_unit_plans_v2(curriculum_version_id,quality_status);
create index if not exists learning_unit_content_v2_phase_idx on public.learning_unit_content_v2(unit_plan_id,phase,display_order);

alter table public.learning_curriculum_versions enable row level security;
alter table public.learning_unit_plans_v2 enable row level security;
alter table public.learning_unit_content_v2 enable row level security;
-- Staging metadata is private until an explicitly reviewed read-only API is shipped.
revoke all on public.learning_curriculum_versions from anon,authenticated;
revoke all on public.learning_unit_plans_v2 from anon,authenticated;
revoke all on public.learning_unit_content_v2 from anon,authenticated;
